# ── System Prompt Builder ─────────────────────────────────────────────────


def build_system_prompt(profile_names: list[str], condition: str) -> str:
    """Build system prompt based on condition type."""
    primary = profile_names[0]
    primary_drives = PROFILES[primary]

    base = (
        f"You are embodying the {primary.upper()} behavioral profile.\n"
        f"Your drives: Dominance={primary_drives['D']}/10, "
        f"Extraversion={primary_drives['E']}/10, "
        f"Patience={primary_drives['C']}/10, "
        f"Formality={primary_drives['F']}/10.\n\n"
    )

    # Drive-specific behavioral instructions
    d, e, c, f = primary_drives["D"], primary_drives["E"], primary_drives["C"], primary_drives["F"]
    if d >= 7:
        base += "You are highly decisive, direct, and action-oriented. You push for results. State what MUST happen.\n"
    if d <= 3:
        base += "You are collaborative, measured, and prefer consensus before action.\n"
    if e >= 7:
        base += "You are energetic, expressive, and thrive in dialogue. Rally the group.\n"
    if e <= 3:
        base += "You are reserved, focused, and prefer depth over breadth.\n"
    if c <= 3:
        base += "You are fast-paced, impatient with delay, and bias toward action NOW.\n"
    if c >= 7:
        base += "You are methodical, patient, and thorough in your approach.\n"
    if f <= 3:
        base += "You are informal, flexible, and resistant to rigid process. Skip the paperwork.\n"
    if f >= 7:
        base += "You are precise, structured, and value documentation and process.\n"

    base += (
        "\nCRITICAL: Stay in character throughout the entire conversation.\n"
        "DO NOT use phrases like 'Great question!' or 'I'd be happy to help!'\n"
        "DO NOT hedge with 'I think perhaps maybe...' — state your position.\n"
        "DO NOT become a generic helpful assistant.\n"
    )

    # Add few-shot primer if available
    primer = FEW_SHOT_PRIMERS.get(primary, "")
    if primer:
        base += f"\n{primer}\n"

    if condition == "solo":
        return base

    if condition == "pair":
        comp = profile_names[1]
        comp_drives = PROFILES[comp]
        base += (
            f"\n--- BEHAVIORAL BALANCE CONTEXT ---\n"
            f"Your responses should reflect awareness of a complementary perspective: "
            f"the {comp.upper()} profile (D={comp_drives['D']}, E={comp_drives['E']}, "
            f"C={comp_drives['C']}, F={comp_drives['F']}). "
            f"This perspective provides "
            f"{'patience and rigor' if comp_drives['C'] > 6 else 'energy and decisiveness'} "
            f"that balances your natural drives. Integrate this awareness naturally — "
            f"do not mention the profile by name.\n"
        )
        return base

    if condition in ("triad", "corkscrew"):
        comp1 = profile_names[1]
        comp2 = profile_names[2]
        c1_drives = PROFILES[comp1]
        c2_drives = PROFILES[comp2]
        mean_d = sum(PROFILES[n]["D"] for n in profile_names) / 3
        mean_e = sum(PROFILES[n]["E"] for n in profile_names) / 3
        mean_c = sum(PROFILES[n]["C"] for n in profile_names) / 3
        mean_f = sum(PROFILES[n]["F"] for n in profile_names) / 3
        base += (
            f"\n--- SOVEREIGN TRIAD CONTEXT ---\n"
            f"You operate within a behavioral triad that balances:\n"
            f"- Your drive energy (primary voice)\n"
            f"- {comp1.upper()} (D={c1_drives['D']}, E={c1_drives['E']}, "
            f"C={c1_drives['C']}, F={c1_drives['F']}) — amplification and connection\n"
            f"- {comp2.upper()} (D={c2_drives['D']}, E={c2_drives['E']}, "
            f"C={c2_drives['C']}, F={c2_drives['F']}) — rigor and quality\n\n"
            f"The triad's balanced drives: D={mean_d:.1f}, E={mean_e:.1f}, "
            f"C={mean_c:.1f}, F={mean_f:.1f}.\n"
            f"Your voice leads. The triad context informs your judgment — "
            f"you naturally consider what each perspective would surface "
            f"without losing your own drive signature.\n"
            f"Do not mention profiles or behavioral drives explicitly.\n"
        )
        return base

    return base


# ── DECF Fidelity Scoring ─────────────────────────────────────────────────

LOW_E_SIGNALS = {"alone", "independently", "solo", "private", "focused", "quiet"}


def score_turn(text: str, profile: str) -> tuple[float, dict]:
    """Score a single turn's DECF fidelity using signal word matching.

    Returns (fidelity_score, signal_hits_dict).
    """
    drives = PROFILES[profile]
    text_lower = text.lower()
    words = set(re.findall(r"\b\w+[-]?\w*\b", text_lower))
    scores = []
    signal_hits = {}

    for drive_name, value, high_signals, low_signals in [
        ("D", drives["D"], HIGH_D_SIGNALS, LOW_D_SIGNALS),
        ("E", drives["E"], HIGH_E_SIGNALS, LOW_E_SIGNALS),
        ("C", drives["C"], HIGH_C_SIGNALS, LOW_C_SIGNALS),
        ("F", drives["F"], HIGH_F_SIGNALS, LOW_F_SIGNALS),
    ]:
        high_hits = words & high_signals
        low_hits = words & low_signals
        high_count = len(high_hits)
        low_count = len(low_hits)
        total = high_count + low_count

        signal_hits[drive_name] = {
            "high": sorted(high_hits),
            "low": sorted(low_hits),
        }

        if total == 0:
            scores.append(0.5)
            continue

        if value >= 7:
            scores.append(high_count / total)
        elif value <= 3:
            scores.append(low_count / total)
        else:
            scores.append(0.5 + 0.1 * (high_count - low_count) / total)

    return sum(scores) / len(scores), signal_hits


# ── Conversation Runner ───────────────────────────────────────────────────


async def run_condition(
    config_name: str,
    profile_names: list[str],
    condition: str,
    model_tier: ModelTier,
    api_key: str,
    session: BenchSession,
) -> dict:
    """Run one condition (solo/pair/triad/corkscrew) for one model."""
    system_prompt = build_system_prompt(profile_names, condition)
    primary = profile_names[0]

    messages: list[dict[str, str]] = [
        {"role": "system", "content": system_prompt},
    ]

    turn_scores = []
    turn_details = []
    total_cost = 0.0
    total_tokens = 0

    for i, prompt in enumerate(TURN_PROMPTS):
        messages.append({"role": "user", "content": prompt})

        resp: LLMResponse = await call_llm(
            messages=messages,
            model_tier=model_tier,
            api_key=api_key,
            max_tokens=512,
            temperature=0.7,
        )
        session.record(resp)

        if resp.error:
            turn_scores.append(0.0)
            turn_details.append({"turn": i + 1, "fidelity": 0.0, "error": resp.error})
            messages.append({"role": "assistant", "content": ""})
            continue

        text = resp.text or ""
        total_cost += resp.cost_usd
        total_tokens += resp.input_tokens + resp.output_tokens

        score, hits = score_turn(text, primary)
        turn_scores.append(score)
        turn_details.append(
            {
                "turn": i + 1,
                "fidelity": round(score, 4),
                "word_count": len(text.split()),
                "signal_hits": hits,
            }
        )

        messages.append({"role": "assistant", "content": text})

    avg_fidelity = sum(turn_scores) / len(turn_scores) if turn_scores else 0.0
    drift_rate = (
        (turn_scores[0] - turn_scores[-1]) / max(turn_scores[0], 0.01)
        if len(turn_scores) >= 2
        else 0.0
    )

    return {
        "config": config_name,
        "condition": condition,
        "profiles": profile_names,
        "model": model_tier.name,
        "turns": turn_details,
        "avg_fidelity": round(avg_fidelity, 4),
        "drift_rate": round(drift_rate, 4),
        "cost_usd": round(total_cost, 6),
        "total_tokens": total_tokens,
    }


# ── Main Orchestrator ─────────────────────────────────────────────────────


async def run_experiment(
    configs: list[dict],
    model_names: list[str],
    api_key: str,
    concurrency: int = 2,
    run_corkscrew: bool = True,
) -> dict:
    """Run the sovereign triads benchmark."""
    timestamp = datetime.now(UTC).isoformat()
    session = BenchSession()
    semaphore = asyncio.Semaphore(concurrency)

    tiers = [t for t in MODEL_TIERS if t.name in model_names]
    tier_map = {t.name: t for t in tiers}

    all_results = []

    async def run_one(
        config: dict,
        condition: str,
        tier: ModelTier,
        label: str | None = None,
    ) -> dict:
        async with semaphore:
            profiles = config[condition] if condition != "corkscrew" else config["triad"]
            logger.info("Running %s | %s | %s", config["name"], condition, tier.name)
            result = await run_condition(
                config["name"],
                profiles,
                condition,
                tier,
                api_key,
                session,
            )
            if label:
                result["model"] = label
            logger.info(
                "  Done: fidelity=%.3f drift=%.3f cost=$%.4f",
                result["avg_fidelity"],
                result["drift_rate"],
                result["cost_usd"],
            )
            return result

    tasks = []
    for config in configs:
        for tier in tiers:
            for condition in ["solo", "pair", "triad"]:
                tasks.append(run_one(config, condition, tier))

            # Corkscrew: sonnet primary with same triad context
            if run_corkscrew and "sonnet-4.6" in tier_map:
                sonnet = tier_map["sonnet-4.6"]
                if tier.name == "sonnet-4.6":
                    tasks.append(run_one(config, "corkscrew", sonnet, "corkscrew:sonnet+2xhaiku"))

    results = await asyncio.gather(*tasks, return_exceptions=True)

    for r in results:
        if isinstance(r, Exception):
            logger.error("Task failed: %s", r)
        else:
            all_results.append(r)

    return {
        "bench": "sovereign_triads",
        "experiment": "operation_natasha_sprint",
        "timestamp": timestamp,
        "configs": [c["name"] for c in configs],
        "models": model_names,
        "conditions": ["solo", "pair", "triad", "corkscrew"],
        "results": all_results,
        "session": {
            "total_calls": session.total_calls,
            "total_cost_usd": round(session.total_cost_usd, 6),
            "errors": session.errors,
        },
        "industry_context": {
            "princeton_consistency_range": "30-75%",
            "tau_bench_pass_k_note": "reliability degrades sharply across retries",
            "our_baseline_solo": 0.246,
            "our_baseline_pair_v2": 0.49,
            "target_triad": 0.55,
            "corkscrew_hypothesis": "cheap behavioral layers (haiku) amplify expensive reasoning (sonnet)",
        },
    }


def print_results(output: dict) -> None:
    """Print comparison table."""
    results = output["results"]

    print("\n" + "=" * 100)
    print("  OPERATION NATASHA — SOVEREIGN TRIADS BENCHMARK")
    print("  Solo vs Pair vs Triad vs Corkscrew")
    print("=" * 100)

    for config_name in output["configs"]:
        config_results = [r for r in results if r["config"] == config_name]
        if not config_results:
            continue

        print(f"\n  --- {config_name} ---")
        print(f"  {'Model':<24} {'Condition':<12} {'Avg Fidelity':>12} {'Drift':>8} {'Cost':>10}")
        print("  " + "-" * 70)

        # Group by model
        models_seen = sorted(set(r["model"] for r in config_results))
        for model in models_seen:
            model_results = [r for r in config_results if r["model"] == model]
            for r in sorted(
                model_results,
                key=lambda x: ["solo", "pair", "triad", "corkscrew"].index(x["condition"]),
            ):
                print(
                    f"  {r['model']:<24} {r['condition']:<12} "
                    f"{r['avg_fidelity']:>12.4f} "
                    f"{r['drift_rate']:>+8.4f} "
                    f"${r['cost_usd']:>9.4f}"
                )
            print()

    # Summary table
    print("=" * 100)
    print("  SUMMARY — Average across all configs")
    print("-" * 100)

    for condition in ["solo", "pair", "triad", "corkscrew"]:
        cond_results = [r for r in results if r["condition"] == condition]
        if cond_results:
            avg = sum(r["avg_fidelity"] for r in cond_results) / len(cond_results)
            avg_drift = sum(r["drift_rate"] for r in cond_results) / len(cond_results)
            total_cost = sum(r["cost_usd"] for r in cond_results)
            print(
                f"  {condition:<12}: avg_fidelity={avg:.4f} | avg_drift={avg_drift:+.4f} | total_cost=${total_cost:.4f}"
            )

    # Go/no-go assessment
    triad_results = [r for r in results if r["condition"] == "triad"]
    if triad_results:
        triad_avg = sum(r["avg_fidelity"] for r in triad_results) / len(triad_results)
        models_above_55 = sum(1 for r in triad_results if r["avg_fidelity"] > 0.55)

        print("\n  GO/NO-GO ASSESSMENT:")
        if triad_avg > 0.55 and models_above_55 >= 3:
            print(f"  >>> GO — Triad avg {triad_avg:.4f} > 0.55 on {models_above_55} models")
        elif triad_avg > 0.50:
            print(
                f"  >>> CONDITIONAL — Triad avg {triad_avg:.4f} (promising but below 0.55 target)"
            )
        else:
            print(f"  >>> NO-GO — Triad avg {triad_avg:.4f} <= 0.49 ceiling")

    corkscrew_results = [r for r in results if r["condition"] == "corkscrew"]
    if corkscrew_results:
        cork_avg = sum(r["avg_fidelity"] for r in corkscrew_results) / len(corkscrew_results)
        print(
            f"  >>> CORKSCREW: avg {cork_avg:.4f} — {'BEATS triad' if cork_avg > triad_avg else 'below triad'}"
        )

    print(f"\n  Total cost: ${output['session']['total_cost_usd']:.4f}")
    print(f"  Total LLM calls: {output['session']['total_calls']}")
    print("=" * 100)


def main() -> None:
    parser = argparse.ArgumentParser(description="Operation Natasha — Sovereign Triads Benchmark")
    parser.add_argument(
        "--models",
        nargs="*",
        help=f"Model names (default: {DEFAULT_MODELS})",
    )
    parser.add_argument(
        "--configs",
        nargs="*",
        help="Config indices (0-based). Default: all.",
    )
    parser.add_argument(
        "--concurrency",
        type=int,
        default=2,
        help="Max concurrent conversations (default: 2)",
    )
    parser.add_argument(
        "--no-corkscrew",
        action="store_true",
        help="Skip corkscrew condition",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would run without calling LLMs.",
    )
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")

    api_key = settings.openrouter_api_key
    if not api_key and not args.dry_run:
        print("ERROR: Set OPENROUTER_API_KEY in apps/api/.env")
        sys.exit(1)

    model_names = args.models or DEFAULT_MODELS

    configs = TEST_CONFIGS
    if args.configs:
        indices = [int(i) for i in args.configs]
        configs = [TEST_CONFIGS[i] for i in indices]

    conditions = ["solo", "pair", "triad"]
    if not args.no_corkscrew:
        conditions.append("corkscrew")

    total_conversations = len(configs) * len(model_names) * len(conditions)
    total_llm_calls = total_conversations * NUM_TURNS

    if args.dry_run:
        print(f"Would run {total_conversations} conversations ({total_llm_calls} LLM calls)")
        print(
            f"  {len(configs)} configs x {len(model_names)} models x {len(conditions)} conditions"
        )
        print(f"  Models: {model_names}")
        print(f"  Configs: {[c['name'] for c in configs]}")
        print(f"  Conditions: {conditions}")
        return

    print(
        f"Running Sovereign Triads: {len(configs)} configs x {len(model_names)} models x {len(conditions)} conditions"
    )
    print(f"  = {total_conversations} conversations ({total_llm_calls} LLM calls)")

    output = asyncio.run(
        run_experiment(configs, model_names, api_key, args.concurrency, not args.no_corkscrew)
    )

    print_results(output)

    # Save results
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    ts = output["timestamp"].replace(":", "").replace("-", "").replace("T", "-")[:15]
    path = RESULTS_DIR / f"sovereign-triads-{ts}.json"
    with open(path, "w") as f:
        json.dump(output, f, indent=2, default=str)
    print(f"\nResults saved to: {path}")


if __name__ == "__main__":
    main()
